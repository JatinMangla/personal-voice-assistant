"""Jarvis Coder: connect this computer's Claude Code to your Coder. One file, nothing to clone.

    python jarvis_coder_installer.py                 # asks for your CODER_KEY
    python jarvis_coder_installer.py --key <key>     # or give it straight away
    python jarvis_coder_installer.py --uninstall     # undo everything this added

The coding model runs on YOUR Kaggle GPU run, reached over the internet, so this machine needs no
GPU, no model download and no Kaggle account: only Python 3.10+, this file and your key. The whole
client is embedded below, so it works on a machine that cannot reach GitHub.

What it does: unpacks the client into ~/.jarvis-coder/client, installs the three packages it needs
(numpy, httpx, mcp), remembers your key so a reboot does not lose it, writes .mcp.json in the folder
you run it in so Claude Code finds the tools, and checks the link.

Only the standard library is used until the packages are installed, so it runs on a bare machine.
This file is GENERATED by scripts/make_coder_installer.py: do not edit it by hand.
"""
import argparse
import base64
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

PAYLOAD = ""
PAYLOAD_SHA256 = ""

PACKAGES = ["numpy", "httpx", "mcp"]
DEFAULT_URL = "https://volley-gnarly-constable.ngrok-free.dev"
MIN_PYTHON = (3, 10)
WINDOWS = os.name == "nt"
KEY_PATTERN = re.compile(r"^[A-Za-z0-9_-]{32,}$")   # what scripts/make_key.py prints
PROFILES = (".zshrc", ".bashrc", ".bash_profile", ".profile")
MARKER = "# jarvis coder client"


def say(step: str, detail: str = "") -> None:
    print(f"[coder] {step}" + (f": {detail}" if detail else ""), flush=True)


def home() -> Path:
    """CODER_HOME if set, else ~/.jarvis-coder -- the same place the client uses for its index."""
    return Path(os.environ.get("CODER_HOME") or Path.home() / ".jarvis-coder")


def client_dir() -> Path:
    return home() / "client"


def check_python() -> None:
    if sys.version_info < MIN_PYTHON:
        sys.exit(f"[coder] This needs Python {MIN_PYTHON[0]}.{MIN_PYTHON[1]} or newer; "
                 f"this is {sys.version.split()[0]}. Install a newer Python and run it again.")


def unpack() -> Path:
    """Write the embedded client to disk. The digest is checked so a truncated copy of this file
    (a bad paste, a half-finished download) fails loudly instead of installing broken code."""
    blob = base64.b64decode("".join(PAYLOAD.split()))
    actual = hashlib.sha256(blob).hexdigest()
    if PAYLOAD_SHA256 and actual != PAYLOAD_SHA256:
        sys.exit("[coder] This file is damaged (the embedded client does not match its checksum). "
                 "Copy it again.")
    target = client_dir()
    if target.exists():
        shutil.rmtree(target, ignore_errors=True)
    target.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(blob)) as zf:
        zf.extractall(target)
    count = len(list(target.rglob("*.py")))
    say("client", f"unpacked {count} files into {target}")
    return target


def pip_install(python: Path | str) -> None:
    missing = [name for name in PACKAGES
               if subprocess.run([str(python), "-c", f"import {name}"],
                                 capture_output=True).returncode]
    if not missing:
        say("packages", "numpy, httpx and mcp are already there")
        return
    say("packages", "installing " + ", ".join(missing))
    base = [str(python), "-m", "pip", "install", "-q"]
    attempts = [base + missing]
    if sys.prefix == sys.base_prefix:        # not in a venv: --user keeps it out of system site
        attempts.insert(0, base + ["--user"] + missing)
    for command in attempts:
        if subprocess.run(command).returncode == 0:
            return
    sys.exit("[coder] Could not install " + ", ".join(missing) + ".\n"
             "        This step is the ONE thing that needs internet access to PyPI. If this\n"
             "        machine blocks PyPI, install them however you normally do, then run this\n"
             "        file again -- everything else works without the internet.")


def ask_for_key() -> str:
    print("\n[coder] Paste your CODER_KEY (from your password manager), or press Enter to skip.")
    try:
        value = input("        CODER_KEY: ").strip().lstrip("﻿").strip()
    except (EOFError, KeyboardInterrupt):
        return ""
    if value and not KEY_PATTERN.match(value):
        print("[coder] That does not look like the key (letters, digits, - and _, 32+ characters)."
              " Nothing was saved.")
        return ""
    return value


def remember_key(key: str) -> None:
    """Save it so a new terminal still has it. No admin rights needed either way."""
    if WINDOWS:
        subprocess.run(["setx", "CODER_KEY", key], capture_output=True)
        say("CODER_KEY", "saved as a user variable (reopen your editor to pick it up)")
        return
    profile = next((Path.home() / n for n in PROFILES if (Path.home() / n).exists()),
                   Path.home() / ".profile")
    text = profile.read_text(encoding="utf-8") if profile.exists() else ""
    if "CODER_KEY" in text:
        say("CODER_KEY", f"already set in {profile.name}; left it alone")
        return
    with profile.open("a", encoding="utf-8") as handle:
        handle.write(f'\n{MARKER}\nexport CODER_KEY="{key}"\n')
    say("CODER_KEY", f"added to {profile.name} (open a new terminal to pick it up)")


def write_mcp_config(target: Path) -> None:
    """.mcp.json in the CURRENT folder, so Claude Code here gets the tools. Any other MCP server
    already in the file is kept: this must never delete someone's existing setup."""
    path = Path.cwd() / ".mcp.json"
    server = {"command": sys.executable,
              "args": [str(target / "coder_mcp.py")],
              "env": {"CODER_URL": "${CODER_URL:-" + DEFAULT_URL + "}",
                      "CODER_KEY": "${CODER_KEY:-}",
                      "PYTHONPATH": str(target)}}
    config = {"mcpServers": {"coder": server}}
    if path.exists():
        try:
            current = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            current = {}
        for name, existing in (current.get("mcpServers") or {}).items():
            if name != "coder":
                config["mcpServers"][name] = existing
    path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    say(".mcp.json", f"written in {path.parent}")


def check_link(target: Path, key: str) -> None:
    code = ("import sys; sys.path.insert(0, r'" + str(target) + "')\n"
            "from coder.client import CoderClient\n"
            "c = CoderClient.from_env()\n"
            "print('[coder] link: ' + (c.link_status() if c else 'CODER_URL/CODER_KEY not set'))\n")
    env = {**os.environ, "CODER_URL": os.environ.get("CODER_URL", DEFAULT_URL)}
    if key:
        env["CODER_KEY"] = key
    result = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, env=env)
    print((result.stdout or result.stderr).strip()[:600])


def uninstall() -> None:
    target = client_dir()
    if target.exists():
        shutil.rmtree(target, ignore_errors=True)
        say("removed", str(target))
    else:
        say("nothing to remove at", str(target))
    path = Path.cwd() / ".mcp.json"
    if path.exists():
        try:
            config = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            config = {}
        servers = config.get("mcpServers") or {}
        if servers.pop("coder", None) is not None:
            if servers:
                config["mcpServers"] = servers
                path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
                say(".mcp.json", "removed the coder entry, kept the others")
            else:
                path.unlink()
                say(".mcp.json", "removed (it held only the coder)")
    print("[coder] The index and your ratings are still in", home(),
          "- delete that folder too if you want them gone.")
    print("[coder] CODER_KEY was left where it was; remove it yourself if you want.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Connect this machine to your Jarvis Coder.")
    parser.add_argument("--key", default="", help="your CODER_KEY, instead of being asked")
    parser.add_argument("--no-save-key", action="store_true", help="do not store the key")
    parser.add_argument("--uninstall", action="store_true", help="undo what this added")
    args = parser.parse_args()

    check_python()
    if args.uninstall:
        uninstall()
        return

    print(f"[coder] python {sys.version.split()[0]} on {sys.platform}, folder {Path.cwd()}")
    target = unpack()
    pip_install(sys.executable)
    write_mcp_config(target)

    key = args.key.strip().lstrip("﻿").strip() or os.environ.get("CODER_KEY", "").strip()
    if key and args.key and not args.no_save_key:
        remember_key(key)
    elif not key:
        key = ask_for_key()
        if key and not args.no_save_key:
            remember_key(key)
    check_link(target, key)

    print("\n[coder] Done. Reopen your editor, then ask Claude Code to run `coder_status`.")
    print("[coder] It reads this folder by default. Your questions and the matching code go to")
    print("        your Kaggle run (Google) and through ngrok; set CODER_ALLOWED_DIRS to limit")
    print("        which folders it may read.")
    print("[coder] 'offline' is normal: the model only runs while you have started it on Kaggle")
    print("        (GitHub -> Actions -> Start Coder). search_code and repo_map work offline.")


if __name__ == "__main__":
    main()
